const NOW = Date.now();

function news(
  id: string,
  title: string,
  source: string,
  category: string,
  symbols: string[],
  impact: AiNewsItem["impact"],
  tone: AiNewsItem["tone"],
  confidence: number,
  expectedDuration: string,
  summary: string,
  content: string,
  hoursAgo: number,
): AiNewsItem {
  return {
    id,
    title,
    source,
    url: "#",
    publishedAt: new Date(NOW - hoursAgo * 3600_000).toISOString(),
    category,
    symbols,
    summary,
    impact,
    tone,
    confidence,
    expectedDuration,
    content,
  };
}

